export function resolveLocale(language: string) {
  const code = language.toLowerCase().split(/[-_]/)[0]
  return code === 'en' || code === 'es' ? code : 'pt'
}
export type MessageKey = keyof typeof messages.pt
export type Translator = (key: MessageKey) => string
export function useT(language = navigator.language): Translator {
  const locale = resolveLocale(language)
  return key => messages[locale][key]
}
